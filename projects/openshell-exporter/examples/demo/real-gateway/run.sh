case "$(uname -s)" in
  Linux)
    if [ -s /etc/ssl/certs/ca-certificates.crt ]; then
      cp /etc/ssl/certs/ca-certificates.crt "$HOST_CA_BUNDLE"
    elif [ -s /etc/ssl/cert.pem ]; then
      cp /etc/ssl/cert.pem "$HOST_CA_BUNDLE"
    else
      echo "host CA bundle is missing" >&2
      exit 1
    fi
    ;;
  Darwin)
    if [ -s /etc/ssl/cert.pem ]; then
      cp /etc/ssl/cert.pem "$HOST_CA_BUNDLE"
    else
      : >"$HOST_CA_BUNDLE"
    fi
    for keychain in \
      /System/Library/Keychains/SystemRootCertificates.keychain \
      /Library/Keychains/System.keychain; do
      [ -r "$keychain" ] || continue
      security find-certificate -a -p "$keychain" >>"$HOST_CA_BUNDLE" 2>/dev/null || true
    done
    ;;
  *)
    echo "unsupported host operating system for CA discovery: $(uname -s)" >&2
    exit 1
    ;;
esac
