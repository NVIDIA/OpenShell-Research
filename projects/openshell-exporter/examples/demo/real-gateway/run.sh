generate_server_certificate() {
  local name=$1
  local common_name=$2
  local subject_alt_name=$3
  openssl req -newkey rsa:3072 -sha256 -nodes \
    -subj "/CN=$common_name" \
    -keyout "$TLS_DIR/$name.key" -out "$TLS_DIR/$name.csr" >/dev/null 2>&1
  printf 'subjectAltName=%s\nextendedKeyUsage=serverAuth\n' "$subject_alt_name" >"$TLS_DIR/$name.ext"
  openssl x509 -req -sha256 -days 30 \
    -in "$TLS_DIR/$name.csr" \
    -CA "$TLS_DIR/ca.crt" -CAkey "$TLS_DIR/ca.key" -CAcreateserial \
    -extfile "$TLS_DIR/$name.ext" \
    -out "$TLS_DIR/$name.crt" >/dev/null 2>&1
}

