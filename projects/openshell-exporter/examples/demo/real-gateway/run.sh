wait_http() {
  local description=$1
  local url=$2
  local attempts=90
  while (( attempts > 0 )); do
    if curl --fail --silent --show-error "$url" >/dev/null 2>&1; then
      echo "$description is ready"
      return 0
    fi
    attempts=$((attempts - 1))
    sleep 1
  done
  echo "$description did not become ready: $url" >&2
  return 1
}
wait_https() {
  local description=$1
  local url=$2
  local ca_file=$3
  local attempts=90
  while (( attempts > 0 )); do
    if curl --fail --silent --show-error --cacert "$ca_file" "$url" >/dev/null 2>&1; then
      echo "$description is ready"
      return 0
    fi
    attempts=$((attempts - 1))
    sleep 1
  done
  echo "$description did not become ready: $url" >&2
  return 1
}

