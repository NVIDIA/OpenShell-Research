# OpenShell 0.0.113 reserves OPENSHELL_* keys and does not inject a sandbox ID
# into sandbox exec processes. Bind the authoritative ID returned by sandbox
# get/create to every Hermes exec through launcher-owned, non-secret variables,
# rather than relying on an operator-configured or workload-invented identifier.
hermes_exec() {
